package sure_cls_gen

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/require"
	"github.com/yylego/rese"
	"github.com/yylego/sure"
)

// Machine hands the codegen a type name to look up
// Its methods live in the scanned source below instead of here, since the codegen
// reads signatures as text out of files on disk and takes nothing besides the name
// from the object
//
// Machine 给生成器一个可查的类型名
// 它的方法在下面那份被扫描的源码里、而不在这儿，因为生成器是从磁盘上的文件里按文本读签名的，
// 从对象身上只取名字
type Machine struct{}

// scannedSource is written into a temp path and scanned from there
//
// Both imports resist guessing on purpose: timekit is an alias no package answers
// to, and the yaml package sits at a path ending in .v3, so the path does not state
// the name and the name does not state the path. Codegen that transcribes these
// signatures without the import block leaves the copied types with no stated origin,
// and anyone who fills them in afterwards has to guess, which this fixture makes
// impossible.
//
// The strconv import checks the reverse: it belongs to the import block and reaches
// no signature, so the taken duplicate has to get pruned instead of settling in.
//
// scannedSource 写进临时目录、并从那里被扫描的源码
//
// 两个导入都故意做成猜不出来的：timekit 是个没有任何包认领的别名，
// yaml 待在以 .v3 结尾的路径下，路径与包名互相推不出来。生成器如果只抄这些签名、
// 不带上导入块，抄来的类型就没有出处，后续无论谁来补都只能靠猜——本用例让猜变得不可能。
//
// strconv 这条用来验反方向：它属于导入块、却没进入任何签名，
// 于是取走的那一份必须被剪掉，不能赖在产物里。
const scannedSource = `package tempsource

import (
	"strconv"

	timekit "time"
	"gopkg.in/yaml.v3"
)

type Machine struct {
	code int
}

func (m *Machine) Convert(span timekit.Duration) (yaml.Node, error) {
	return yaml.Node{Value: strconv.Itoa(m.code)}, nil
}

func (m *Machine) Assemble(nodes []yaml.Node) (*timekit.Duration, error) {
	span := timekit.Duration(len(nodes))
	return &span, nil
}
`

// TestGenerateCarriesSourceImports checks the scanned import block reaches the output
// Checks it with nothing registered at hand
//
// Everything lands in a temp path. A generated file that stops compiling inside this
// module would take its package down, codegen test included, which is the deadlock
// this work exists to remove.
//
// TestGenerateCarriesSourceImports 检查被扫描文件的导入块会进入生成代码
// 检查时全程不手工登记任何东西
//
// 一切都落在临时目录里。生成的文件若在本模块内编译不过，会把它所在的包一起拖垮、
// 连生成器测试自己都跑不起来——这正是本次工作要根除的那个僵局。
func TestGenerateCarriesSourceImports(t *testing.T) {
	sourceRoot := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(sourceRoot, "tempsource.go"), []byte(scannedSource), 0644))

	outputPath := filepath.Join(t.TempDir(), "sure.gen.go")
	GenerateClasses(&ClassGenConfig{
		ClassGenOptions: NewClassGenOptions(sourceRoot).MoreErrorHandlingModes(sure.MUST),
		PackageName:     "tempsource",
		OutputPath:      outputPath,
	}, Machine{})

	generatedCode := string(rese.V1(os.ReadFile(outputPath)))
	t.Log("\n" + generatedCode)

	// The alias has to move with its path, else timekit.Duration has no origin
	// 别名必须跟着路径一起走，否则 timekit.Duration 无处可寻
	require.Contains(t, generatedCode, `timekit "time"`)
	// The versioned path cannot be deduced from the package name
	// 版本化路径没法从包名推出来
	require.Contains(t, generatedCode, `"gopkg.in/yaml.v3"`)
	// Taken along and left unused, so it has to be gone again
	// 取过来却没用上，所以必须再消失
	require.NotContains(t, generatedCode, `"strconv"`)
	// The escape hatch that keeps a broken artifact from locking its own package
	// 那道让破损产物无法卡住自身所在包的退路
	require.Contains(t, generatedCode, "//go:build "+sure.DirectiveSkipGenerate)
}

// Gadget stands in a source file headed with the shared generated-code mark
// Gadget 所在的源文件顶着通用的"机器生成"标记
type Gadget struct{}

// foreignSource carries the mark protoc-gen-go and its peers write
//
// Such code is just what people want a wrapping class around, so a scan has to keep
// reaching it. The scan skips one file alone, the artifact about to get overwritten,
// which leaves a class generated here open to a stub pass afterwards too.
//
// foreignSource 顶着 protoc-gen-go 之类写下的那行标记
//
// 这类代码恰恰是人们最想拿来做包装的，所以必须照常可扫。
// 扫描只跳过一个文件——即将被覆写的那个产物——这也让这里生成出的类之后仍能再走一遍存根生成。
const foreignSource = `// Code generated by protoc-gen-go. DO NOT EDIT.

package tempsource

type Gadget struct{}

func (g *Gadget) Fetch() (int, error) {
	return 0, nil
}
`

// TestGenerateScansForeignGeneratedCode checks a foreign artifact does get wrapped
// A wrapping class with no methods and no complaint is the outcome this rules out
//
// TestGenerateScansForeignGeneratedCode 检查别家工具的产物照样会被包装
// 这条排除的正是"生成出一个空包装类、还一声不吭"那种结果
func TestGenerateScansForeignGeneratedCode(t *testing.T) {
	sourceRoot := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(sourceRoot, "tempsource.go"), []byte(foreignSource), 0644))

	outputPath := filepath.Join(t.TempDir(), "sure.gen.go")
	GenerateClasses(&ClassGenConfig{
		ClassGenOptions: NewClassGenOptions(sourceRoot).MoreErrorHandlingModes(sure.MUST),
		PackageName:     "tempsource",
		OutputPath:      outputPath,
	}, Gadget{})

	generatedCode := string(rese.V1(os.ReadFile(outputPath)))
	t.Log("\n" + generatedCode)

	require.Contains(t, generatedCode, "func (T *GadgetMust) Fetch() (res int)")
}
