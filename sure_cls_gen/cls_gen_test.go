// RecvSample carries a method whose input is named T, exercising the wrapping
// receiving name: a hardcoded `T` recv would collide with that input.
//
// RecvSample 带一个参数名为 T 的方法，用于检验包装方法的接收者命名：
// 若接收者硬编码为 T，就会和该参数撞车。
type RecvSample struct{}

// Convert has an input named T on purpose.
//
// Convert 故意带一个名为 T 的参数。
func (a *RecvSample) Convert(T int) (int, error) { return T, nil }

// TestClassReceiverAvoidsCollision guards that the generated wrapping method recv
// avoids two clashes: it must not match an input name (RecvSample.Convert has an
// input named T, so a bare T recv would collide) and must not match the field name
// (else the method text emits a.a). The recv is kept distinct from both.
//
// TestClassReceiverAvoidsCollision 守护生成的包装方法接收者避开两类冲突：不能等于参数名
// （RecvSample.Convert 带一个名为 T 的参数，裸用 T 接收者会撞车），也不能等于字段名
// （否则方法体出现 a.a）。接收者与二者都保持不同。
func TestClassReceiverAvoidsCollision(t *testing.T) {
	cfg := NewClassGenOptions(runpath.PARENT.Path()).
		WithNewClassNameParts("88").
		WithNamingPatternType(STYLE_SUFFIX_CAMELCASE_TYPE).
		WithReceiverVariableName("a")

	code := GenerateClassWithErrorHandlingMode(cfg, RecvSample{}, sure.MUST)

	require.NotContains(t, code, "func (T *", "the wrapping recv must not collide with the input named T")
	require.NotContains(t, code, "func (a *", "the wrapping recv must diverge from the field name (avoid a.a)")
	require.NotContains(t, code, "a.a.Convert", "the method text must not emit a.a")
	require.Contains(t, code, "Convert(T int)", "the input must get forwarded just the same")
	require.Contains(t, code, "sure.Must(", "the error must be asserted")
}

// ResSample carries a method whose input is named res, exercising the
// synthesized-return-name avoidance: the anonymous int return is auto-named
// "res" via GetSimpleResElements and would collide with that input.
//
// ResSample 带一个参数名为 res 的方法，用于检验合成返回值名的避让：
// 匿名的 int 返回会被 GetSimpleResElements 自动命名为 "res"，与该形参撞车。
type ResSample struct{}

// Get has an input named res on purpose; its anonymous int return would also
// be named res without collision avoidance.
//
// Get 故意带一个名为 res 的参数；若不做避让，匿名的 int 返回也会被命名为 res。
func (a *ResSample) Get(res string) (int, error) { return 0, nil }

// TestClassResultNameAvoidsParamCollision guards that a synthesized return-value
// name does not clash with an input name. Without the guard, ResSample.Get
// emits `func (T *X) Get(res string) (res int) { res, err1 := T.a.Get(res) ... }`
// — the named return res redeclares the param res (and the := collides), which
// does not compile. Mirrors the same protection sure_pkg_gen holds.
//
// TestClassResultNameAvoidsParamCollision 守护合成返回值名不与形参名撞车。
// 若无此保护，ResSample.Get 会生成 `func (T *X) Get(res string) (res int){ res, err1 := T.a.Get(res) ... }`
// —— 具名返回 res 与形参 res 重复声明（且 := 撞车），编译不过。与 sure_pkg_gen 已有的保护一致。
func TestClassResultNameAvoidsParamCollision(t *testing.T) {
	cfg := NewClassGenOptions(runpath.PARENT.Path()).
		WithNewClassNameParts("88").
		WithNamingPatternType(STYLE_SUFFIX_CAMELCASE_TYPE)

	code := GenerateClassWithErrorHandlingMode(cfg, ResSample{}, sure.MUST)

	require.Contains(t, code, "Get(res string)", "the input must get preserved")
	require.NotContains(t, code, "(res int)", "the synthesized return must not reuse the input name res")
	require.Contains(t, code, "res0", "the colliding return name must be renamed")
	require.Contains(t, code, "sure.Must(", "the error must get asserted just the same")
}

// BlankSample carries a method with a blank recv, exercising recv-name
// detection: "_" must not be taken as the wrapping's field name.
//
// BlankSample 带一个空白接收者的方法，用于检验接收者名探测："_" 不能被当成包装类的字段名。
type BlankSample struct{}

// Do uses a blank recv on purpose.
//
// Do 故意使用空白接收者。
func (_ *BlankSample) Do(x int) (int, error) { return x, nil } //nolint:staticcheck // keep blank recv token in source so the test can scan it

// TestClassBlankReceiverFallsBackToT guards that a blank recv "_" on the
// wrapped type does not leak into the generated struct field and entrance.
// Without the guard the field name becomes "_", emitting `struct{ _ *BlankSample }`
// and `&X{_:_}` (using _ as a value) and `T._` — none of which compile. The name
// must drop back to "T".
//
// TestClassBlankReceiverFallsBackToT 守护被包装类型的空白接收者 "_" 不泄漏进生成的结构体字段与构造器。
// 若无此保护，字段名会变成 "_"，生成 `struct{ _ *BlankSample }`、`&X{_:_}`（把 _ 当值）、`T._`——全都编译不过。
// 名字必须回退到 "T"。
func TestClassBlankReceiverFallsBackToT(t *testing.T) {
	cfg := NewClassGenOptions(runpath.PARENT.Path()).
		WithNewClassNameParts("88").
		WithNamingPatternType(STYLE_SUFFIX_CAMELCASE_TYPE)

	code := GenerateClassWithErrorHandlingMode(cfg, BlankSample{}, sure.MUST)

	require.NotContains(t, code, "_ *BlankSample", "a blank recv must not become the struct field")
	require.NotContains(t, code, "{_:_}", "must not emit &X{_:_}")
	require.Contains(t, code, "T *BlankSample", "the recv variable name should drop back to T")
	require.Contains(t, code, "sure.Must(", "the error must be asserted")
}

// BlankBox gives the blank-name check a type name to look up
// BlankBox 给"空白名"用例一个可查的类型名
type BlankBox struct{}

// TestClassBlankNames guards that a blank "_" input and a blank result each get a name in the wrapping method
// The wrapping reads each result back and passes each input on, and `return _` / `sure.Must(_)` / `T.b.F(_)` cannot compile
//
// TestClassBlankNames 守护叫 "_" 的参数和返回值在包装方法里都有名字
// 包装要读回每个返回值、传下每个参数，而 `return _` / `sure.Must(_)` / `T.b.F(_)` 编译不过
func TestClassBlankNames(t *testing.T) {
	sourceRoot := t.TempDir()
	src := `package tempsource

type BlankBox struct{}

func (b *BlankBox) Count() (_ int, err error) { return 0, nil }

func (b *BlankBox) Check() (n int, _ error) { return 0, nil }

func (b *BlankBox) Take(_ int, s string) error { return nil }
`
	require.NoError(t, os.WriteFile(filepath.Join(sourceRoot, "tempsource.go"), []byte(src), 0644))

	code := GenerateClassWithErrorHandlingMode(NewClassGenOptions(sourceRoot), BlankBox{}, sure.MUST)
	t.Log("\n" + code)

	require.Contains(t, code, "Count()(res int)")
	require.Contains(t, code, "return res")
	require.Contains(t, code, "n, err:=T.b.Check()")
	require.Contains(t, code, "sure.Must(err)")
	require.Contains(t, code, "Take(arg0 int, s string)")
	require.Contains(t, code, "T.b.Take(arg0, s)")
}

// Widget gives the regeneration checks a type name to look up
// Widget 给"重新生成"这组用例一个可查的类型名
type Widget struct{}

// widgetSource is the source the codegen scans, written into a temp path
// widgetSource 是生成器要扫描的源码，写进临时目录
const widgetSource = `package tempsource

type Widget struct{}

func (w *Widget) Fetch() (int, error) {
	return 0, nil
}
`

// generateWidgetClasses writes the artifact beside the source and hands its path back
//
// The artifact belongs in the source root on purpose, since that is the shape sure_cls_gen produces: a wrapping class has to sit in the package holding the wrapped type
// It also puts the artifact in reach of the next scan, which is what these checks are about
//
// generateWidgetClasses 把产物写在源码旁边，并把产物路径返回
//
// 产物就该落在源码目录里，因为 sure_cls_gen 本来就是这个形状：包装类必须与被包装类型同包
// 这也让产物落进下一轮扫描的射程，而这正是本组用例要查的地方
func generateWidgetClasses(t *testing.T, sourceRoot string, modes ...sure.ErrorHandlingMode) string {
	t.Helper()
	outputPath := filepath.Join(sourceRoot, "sure.gen.go")
	GenerateClasses(&ClassGenConfig{
		ClassGenOptions: NewClassGenOptions(sourceRoot).MoreErrorHandlingModes(modes...),
		PackageName:     "tempsource",
		OutputPath:      outputPath,
	}, Widget{})
	return outputPath
}

// TestGenerateClassCodeWithErrorHandling checks each mode gets a class of its own, Must and Soft as the default
// TestGenerateClassCodeWithErrorHandling 检查每种模式各生成一个类，默认是 Must 和 Soft
func TestGenerateClassCodeWithErrorHandling(t *testing.T) {
	sourceRoot := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(sourceRoot, "tempsource.go"), []byte(widgetSource), 0644))

	code := GenerateClassCodeWithErrorHandling(NewClassGenOptions(sourceRoot), Widget{})
	t.Log("\n" + code)

	// The code comes back ahead of gofmt, hence no space between the two groups
	// 这里拿到的是还没经过 gofmt 的代码，所以两组括号之间没有空格
	require.Contains(t, code, "func (T *WidgetMust) Fetch()(res int)")
	require.Contains(t, code, "func (T *WidgetSoft) Fetch()(res int)")
	require.NotContains(t, code, "WidgetOmit")
}

// TestRegenerateNarrowedModesWritesNoStaleEntrance checks a run that states less modes than the run before it leaves nothing behind pointing at a class it stopped writing
//
// The artifact holds one entrance method from each mode (Must/Soft/Omit) on the wrapped type, so a scan reaching it reads those as source methods and wraps the wrapping
// Narrowing the mode set is where that bites: the stale Omit entrance gets transcribed into an invocation of a WidgetOmit class this run stopped generating, and the artifact stops compiling
// Nothing downstream catches it, since the imports remain above board and MustKnownImports has no complaint to make
//
// TestRegenerateNarrowedModesWritesNoStaleEntrance 检查"模式比上一轮少"的这一趟，不会留下任何指向"它已不再生成的类"的东西
//
// 产物里每个模式都在被包装类型上留了一个入口方法（Must/Soft/Omit），扫描一旦读到它，就会把这些当成源方法、给包装再包一层
// 缩减模式集时最要命：残留的 Omit 入口会被抄成一句"调用本轮已不再生成的 WidgetOmit 类"，产物当场编译不过
// 下游没人拦得住——导入全都清清白白，MustKnownImports 无话可说
func TestRegenerateNarrowedModesWritesNoStaleEntrance(t *testing.T) {
	sourceRoot := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(sourceRoot, "tempsource.go"), []byte(widgetSource), 0644))

	outputPath := generateWidgetClasses(t, sourceRoot, sure.MUST, sure.SOFT, sure.OMIT)
	require.Contains(t, string(rese.V1(os.ReadFile(outputPath))), "WidgetOmit")

	// The same source root, this time with Omit left out
	// 同一个源目录，这一趟不要 Omit
	outputPath = generateWidgetClasses(t, sourceRoot, sure.MUST, sure.SOFT)

	generatedCode := string(rese.V1(os.ReadFile(outputPath)))
	t.Log("\n" + generatedCode)

	require.NotContains(t, generatedCode, "WidgetOmit")
	require.NotContains(t, generatedCode, "Omit()")
	// The methods that belong keep on coming through
	// 该在的方法照常出现
	require.Contains(t, generatedCode, "func (T *WidgetMust) Fetch() (res int)")
	require.Contains(t, generatedCode, "func (T *WidgetSoft) Fetch() (res int)")
}

// TestRegenerateReplacesABrokenArtifact checks a run gets through with an artifact on disk that cannot get parsed, and replaces it
//
// This is the deadlock sure.DirectiveSkipGenerate exists to break, and the build constraint alone does not break it
// The constraint keeps the build off the broken file, while the codegen reads the source root off the filesystem, where no build tag holds
// Parsing asserts, so the run meant to write the replacement dies ahead of writing it, and the sole escape left is hand-editing a file headed DO NOT EDIT
//
// TestRegenerateReplacesABrokenArtifact 检查磁盘上躺着一个解析不了的产物时，这一趟仍能跑通并把它替换掉。
//
// 这正是 sure.DirectiveSkipGenerate 要解开的僵局，而光有构建约束解不开
// 约束挡住的是编译器，生成器却是照文件系统读源目录的，那里没有构建标签这回事
// 解析带断言，于是"本该写出替换版本"的那一趟先崩在写之前，剩下的唯一出路就是手工去改一个写着"请勿编辑"的文件
func TestRegenerateReplacesABrokenArtifact(t *testing.T) {
	sourceRoot := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(sourceRoot, "tempsource.go"), []byte(widgetSource), 0644))

	outputPath := filepath.Join(sourceRoot, "sure.gen.go")
	require.NoError(t, os.WriteFile(outputPath, []byte("package tempsource\n\nfunc broken( {\n"), 0644))

	require.NotPanics(t, func() {
		generateWidgetClasses(t, sourceRoot, sure.MUST)
	})

	generatedCode := string(rese.V1(os.ReadFile(outputPath)))
	t.Log("\n" + generatedCode)

	_, err := parser.ParseFile(token.NewFileSet(), outputPath, generatedCode, parser.AllErrors)
	require.NoError(t, err)
	require.Contains(t, generatedCode, "func (T *WidgetMust) Fetch() (res int)")
}
